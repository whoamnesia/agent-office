// Bundles the plugin runtime: hook emitter, daemon, CLI and relay into plugin/.
import { build } from 'esbuild';
import fs from 'node:fs';
import path from 'node:path';

const root = path.resolve(import.meta.dirname, '..');
const plugin = path.join(root, 'plugin');
const common = { bundle: true, platform: 'node', target: 'node20', legalComments: 'none', logLevel: 'warning' };

await build({
  ...common,
  entryPoints: [path.join(root, 'packages/daemon/src/emit.ts')],
  outfile: path.join(plugin, 'bin/ao-emit'),
  format: 'cjs',
  minify: true,
  banner: {
    js: "#!/usr/bin/env node\n// Agent Office hook emitter (generated by scripts/bundle.mjs). Always exits 0, prints nothing.\ntry{require('node:module').enableCompileCache?.(require('node:path').join(require('node:os').tmpdir(),'agent-office-cc'))}catch{}",
  },
});

await build({
  ...common,
  entryPoints: [path.join(root, 'packages/daemon/src/statusline.ts')],
  outfile: path.join(plugin, 'bin/ao-statusline'),
  format: 'cjs',
  minify: true,
  banner: { js: '#!/usr/bin/env node\n// Agent Office status line (optional, see README).' },
});

for (const [entry, out] of [
  ['packages/daemon/src/main.ts', 'dist/daemon.mjs'],
  ['packages/daemon/src/cli.ts', 'dist/cli.mjs'],
  ['packages/relay/src/node.ts', 'dist/relay.mjs'],
]) {
  if (!fs.existsSync(path.join(root, entry))) continue;
  await build({
    ...common,
    entryPoints: [path.join(root, entry)],
    outfile: path.join(plugin, out),
    format: 'esm',
    minify: false,
    banner: { js: "import { createRequire as __cr } from 'node:module'; const require = __cr(import.meta.url);" },
  });
}

const shim = (target) => `#!/usr/bin/env node\n// Generated by scripts/bundle.mjs\nimport(require('node:url').pathToFileURL(require('node:path').join(__dirname, '..', 'dist', '${target}')).href);\n`;
fs.writeFileSync(path.join(plugin, 'bin/ao-daemon'), shim('cli.mjs'));
fs.writeFileSync(path.join(plugin, 'bin/agent-office'), shim('cli.mjs'));
for (const f of ['ao-emit', 'ao-daemon', 'agent-office', 'ao-statusline']) fs.chmodSync(path.join(plugin, 'bin', f), 0o755);
const size = (f) => (fs.statSync(path.join(plugin, f)).size / 1024).toFixed(1) + ' KB';
console.log('bundled: bin/ao-emit', size('bin/ao-emit'), '| dist/daemon.mjs', size('dist/daemon.mjs'), '| dist/cli.mjs', size('dist/cli.mjs'));
