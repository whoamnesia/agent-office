export function textWidth(s: string): number {
  return s.length * 4 - 1;
}

export function drawText(img: Img, x: number, y: number, s: string, c: RGBA, scale = 1): void {
  let cx = x;
  for (const ch of s.toUpperCase()) {
    const g = G[ch] ?? G[' ']!;
    for (let j = 0; j < 5; j++) for (let i = 0; i < 3; i++) if (g[j * 3 + i] === '1') img.rect(cx + i * scale, y + j * scale, scale, scale, c);
    cx += 4 * scale;
  }
}
